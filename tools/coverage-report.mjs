#!/usr/bin/env node
// coverage-report.mjs [--check] [--details]: writes COVERAGE.md from the built entries, coverage/exclusions.json and the hazard
// registry, and fails when the accounting does not close:
//   - every union arm reachable from LedgerCloseMeta (stellar-xdr v30.0) is either reached by an entry (atoms.mjs:
//     its own transaction or its ledger's shape) or classified in coverage/exclusions.json, never both, never neither;
//   - every hazard is targeted by an entry or belongs, by its checks, to a later stage (conformance, guide, verify).
// --check: fail if COVERAGE.md differs from what would be written (for CI).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { atoms as typeAtoms } from './walker.mjs';
import { ROOT, DEFS, loadEntries, entryAtoms } from './atoms.mjs';
import { makeUI } from './ui.mjs';

const check = process.argv.includes('--check'), DETAILS = process.argv.includes('--details') || process.argv.includes('-v');
const ui = makeUI(), T0 = Date.now();
const ex = JSON.parse(readFileSync(join(ROOT, 'coverage/exclusions.json'), 'utf8'));
const registry = JSON.parse(readFileSync(join(ROOT, 'caps/registry.json'), 'utf8'));
const { arms: allArms, enums: allEnums } = typeAtoms(DEFS, ['LedgerCloseMeta']);
let entries;
try { entries = loadEntries(); } catch (e) { ui.out('  ' + ui.bad(ui.trunc(e.message, ui.width - 4))); ui.verdict('fail', 'ERROR', 'Could not read the corpus', Date.now() - T0); process.exit(2); }
ui.header(check ? 'coverage-report --check' : 'coverage-report', [`${ui.num(allArms.size)} union arms · ${registry.hazards.length} hazards · ${entries.length} entries`, `${ui.num(allArms.size)} arms · ${registry.hazards.length} hazards`, '']);
const row = ui.task('Reading every entry').note('hashing transactions');
let atoms;
try { ({ atoms } = await entryAtoms(entries, { onProgress: (d, n) => row.count(d, n) })); }
catch (e) { row.fail(); ui.clear(); ui.out('  ' + ui.bad(ui.trunc(e.message, ui.width - 4))); ui.verdict('fail', 'ERROR', 'Could not read the corpus', Date.now() - T0); process.exit(2); }
row.done();

// who reaches what
const byArm = new Map(), byEnum = new Map(), byHazard = new Map();
for (const e of entries) for (const a of atoms.get(e.id)) {
  const [k, rest] = [a.slice(0, 2), a.slice(2)];
  const m = k === 'U:' ? byArm : k === 'E:' ? byEnum : k === 'H:' ? byHazard : null;
  if (m) { if (!m.has(rest)) m.set(rest, []); m.get(rest).push(e.id); }
}

// the accounting must close
const problems = [];
const classified = new Map(ex.arms.map((x) => [x.arm, x]));
for (const a of allArms) {
  if (byArm.has(a) && classified.has(a)) problems.push(`${a}: reached by ${byArm.get(a)[0]} but still classified as ${classified.get(a).class} (remove it from coverage/exclusions.json)`);
  if (!byArm.has(a) && !classified.has(a)) problems.push(`${a}: reached by no entry and not classified`);
}
for (const a of classified.keys()) if (!allArms.has(a)) problems.push(`${a}: classified but not an arm reachable from LedgerCloseMeta`);
for (const a of byArm.keys()) if (!allArms.has(a)) problems.push(`${a}: reached but not in the type graph (wrong definitions?)`);
for (const x of ex.arms) if (!ex.classes[x.class]) problems.push(`${x.arm}: unknown class ${x.class}`);
const LATER = { C: 'conformance (lane S vectors, B5)', G: 'the guide (B8)', V: 'the release channel (B9)', R: 'replay (B6)', L: 'the linter (B7)' };
const untargeted = registry.hazards.filter((h) => !byHazard.has(h.id));
for (const h of untargeted) if (!(h.checks ?? []).some((c) => c !== 'V' || h.id === 'H-G4')) problems.push(`${h.id}: targeted by no entry and no later check`);

// ---- render ----
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => '`' + String(s).replace(/`/g, "'") + '`';
const ev = (e) => { const m = e.match(/^(\S+?:\d+(?:-\d+)?)\s+(.*)$/); return m ? `${code(m[1])} ${code(m[2])}` : code(e); };
const list = (ids, n = 3) => ids.slice(0, n).map(code).join(', ') + (ids.length > n ? ` (+${ids.length - n})` : '');
const ORDER = ['todo', 'network-only', 'historical', 'validation-only', 'not-emitted'];
const count = (c) => ex.arms.filter((x) => x.class === c).length;
const reachedEnums = [...allEnums].filter((m) => byEnum.has(m)).length;

const out = [];
out.push('# Coverage', '',
  'Generated by `make coverage-report` (`tools/coverage-report.mjs`) from `entries/`, `coverage/exclusions.json` and',
  '`caps/registry.json`. Do not edit by hand.', '',
  'An entry *reaches* an arm when its own transaction (envelope, fee changes, apply meta) or its ledger\'s shape (header,',
  'transaction-set phases, upgrades, evicted keys) contains it, in any of its variants. Other transactions that share the',
  'container ledger count for nothing. Every arm no entry reaches is classified with the stellar-core source line that',
  'decides it.', '',
  '## Union arms', '',
  `${allArms.size} union arms are reachable from \`LedgerCloseMeta\` in stellar-xdr v30.0.`, '',
  '| | Arms |', '|---|---:|',
  `| Reached by an entry | ${byArm.size} |`,
  ...ORDER.map((c) => `| ${c}: ${ex.classes[c]} | ${count(c)} |`),
  `| **Total** | **${byArm.size + ex.arms.length}** |`, '',
  `Unclassified: ${[...allArms].filter((a) => !byArm.has(a) && !classified.has(a)).length}. Enum members reached: ${reachedEnums} of ${allEnums.size}.`, '',
  `Classification method: ${ex.method}`, '');

out.push('## Hazards', '',
  `${registry.hazards.length} hazards in \`caps/registry.json\`; ${registry.hazards.length - untargeted.length} are targeted by corpus entries.`, '',
  '| Hazard | Entries |', '|---|---|',
  ...registry.hazards.filter((h) => byHazard.has(h.id)).map((h) => `| ${h.id} ${cell(h.title)} | ${byHazard.get(h.id).length}: ${list(byHazard.get(h.id), 2)} |`), '');
if (untargeted.length) out.push('Not corpus hazards: these are about invalid input, prose or release policy, so no valid ledger can carry them.', '',
  '| Hazard | Covered by |', '|---|---|',
  ...untargeted.map((h) => `| ${h.id} ${cell(h.title)} | ${(h.checks ?? []).map((c) => LATER[c] ?? c).join(', ')} |`), '');

out.push(`## Arms no entry reaches (${ex.arms.length})`, '');
for (const c of ORDER) {
  const rows = ex.arms.filter((x) => x.class === c).sort((a, b) => a.arm.localeCompare(b.arm));
  if (!rows.length) continue; // an empty class stays in the summary table above
  out.push(`### ${c} (${rows.length})`, '', ex.classes[c] + '.', '', '| Arm | Why | Source |', '|---|---|---|',
    ...rows.map((x) => `| ${code(x.arm)} | ${cell(x.note)}${x.review.startsWith('corrected') ? ' *(class corrected after source check)*' : ''} | ${x.evidence.map((e) => cell(ev(e))).join('<br>')} |`), '');
}
out.push(`## Arms the entries reach (${byArm.size})`, '', '| Arm | Entries |', '|---|---|',
  ...[...byArm.keys()].sort().map((a) => `| ${code(a)} | ${byArm.get(a).length}: ${list(byArm.get(a))} |`), '');
const text = out.join('\n');

// ---- the cards ----------------------------------------------------------------------------------------------
ui.clear();
const narrow = ui.width < 60, file = join(ROOT, 'COVERAGE.md');
const stale = check && (!existsSync(file) || readFileSync(file, 'utf8') !== text);
const armProblems = problems.filter((x) => !x.startsWith('H-')), hazardProblems = problems.filter((x) => x.startsWith('H-'));
const explained = ex.arms.filter((x) => allArms.has(x.arm) && !byArm.has(x.arm)).length;
const PLAIN = { 'network-only': 'only on the live network', historical: 'only in older protocols', 'validation-only': 'refused before a ledger closes', 'not-emitted': 'never written by core 30', todo: 'not yet in an entry' };
ui.card({
  title: narrow ? 'Every arm accounted' : 'Every union arm reached or explained', score: `${allArms.size - armProblems.filter((x) => x.includes('not classified')).length}/${allArms.size}`,
  lines: [
    ...(armProblems.length ? [{ mark: '✗', text: `${armProblems.length} not accounted for`, detail: armProblems }] : []),
    { mark: '✓', text: `${byArm.size} reached by an entry` },
    { mark: count('todo') ? '!' : '✓', text: narrow ? `${explained} explained` : `${explained} not reached, each with core's reason`,
      detail: ORDER.filter((c) => count(c)).map((c) => `${count(c)} ${PLAIN[c] ?? c}`) },
  ], details: DETAILS || armProblems.length > 0,
});
const targeted = registry.hazards.length - untargeted.length;
ui.card({
  title: narrow ? 'Every hazard covered' : 'Every hazard covered somewhere', score: `${registry.hazards.length - hazardProblems.length}/${registry.hazards.length}`,
  lines: [
    ...(hazardProblems.length ? [{ mark: '✗', text: `${hazardProblems.length} covered nowhere`, detail: hazardProblems }] : []),
    { mark: '✓', text: `${targeted} in a corpus entry` },
    ...(untargeted.length ? [{ mark: '✓', text: narrow ? `${untargeted.length} left to other checks` : `${untargeted.length} left to other checks or the guide`,
      detail: untargeted.map((h) => `${h.id} ${(h.checks ?? []).map((c) => LATER[c]?.replace(/ \(.*\)$/, '') ?? c).join(', ')}`) }] : []),
  ], details: DETAILS || hazardProblems.length > 0,
});
if (problems.length) {
  ui.verdict('fail', 'FAILED', 'The coverage accounting does not close', Date.now() - T0);
  process.exit(1);
}
if (stale) {
  ui.out('  ' + ui.bad('COVERAGE.md is out of date.') + ui.dim('  run: make coverage-report'));
  ui.verdict('fail', 'FAILED', 'COVERAGE.md differs from the corpus', Date.now() - T0);
  process.exit(1);
}
if (!check) writeFileSync(file, text);
ui.verdict('gold', 'PASSED', check ? 'COVERAGE.md is up to date.' : 'COVERAGE.md written.', Date.now() - T0);
if (!DETAILS) ui.hint('why each arm is not reached', 'make coverage-report DETAILS=1');
