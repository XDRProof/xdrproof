#!/usr/bin/env node
// matrix.mjs <adapter>: the recorded result of the last `make replay`, from replay/runs/<adapter>@*/report.json,
// replay/sightings.json and replay/expectations/. Prints Markdown (replay/recorded/<adapter>.md).
import { readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const adapter = process.argv[2] ?? 'wallet-backend';
const report = (t) => { const f = join(HERE, 'runs', `${adapter}@${t}`, 'report.json'); return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null; };
const expect = (t) => { const f = join(HERE, 'expectations', `${adapter}@${t}.json`); return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : { verdicts: {} }; };
const verdictOf = (r, vid) => r?.sessions.find((s) => s.variants.includes(vid)) ?? (r?.unsupported?.[vid] ? { verdict: 'unsupported' } : null);
const kinds = (s) => [...new Set((s?.failures ?? []).map((f) => f.kind))].sort();
const out = [];

const main = report('main');
out.push(`# Replay: ${adapter}`, '');
out.push('Generated by `node replay/matrix.mjs` from the last `make replay`. Every verdict below is pinned in',
  '`replay/expectations/`; a run that differs fails.', '');

// ---- sightings --------------------------------------------------------------------------------------------
const S = JSON.parse(readFileSync(join(HERE, 'sightings.json'), 'utf8')).sightings;
out.push('## Upstream failures, before and after their fixes', '',
  '| Issue | Ledger | Commit | Verdict | Probes that failed |', '|---|---|---|---|---|');
for (const s of S) {
  const issue = s.issue.replace('https://github.com/stellar/wallet-backend/', '').replace('issues/', '#').replace('pull/', '#');
  for (const [ref, why] of Object.entries(s.verdicts)) {
    const r = report(ref);
    const got = s.variants.map((v) => verdictOf(r, v)).filter(Boolean);
    const vs = [...new Set(got.map((g) => g.verdict))].join(', ') || 'not run';
    const ks = [...new Set(got.flatMap(kinds))].join(', ');
    out.push(`| [${issue}](${s.issue}) | ${s.what} (${s.variants.length} variant${s.variants.length > 1 ? 's' : ''}) | \`${ref}\` | **${vs}** | ${ks || '—'} |`);
  }
}
out.push('');

// ---- main ------------------------------------------------------------------------------------------------
if (main) {
  const e = expect('main');
  const all = new Map();
  for (const s of main.sessions) for (const v of s.variants) all.set(v, s);
  const count = {};
  for (const s of all.values()) count[s.verdict] = (count[s.verdict] ?? 0) + 1;
  out.push(`## The whole corpus against \`main\` (${main.ref.slice(0, 8)})`, '',
    `${all.size} variants in ${main.sessions.length} sessions: ` + Object.entries(count).sort().map(([k, v]) => `${v} ${k}`).join(', ') + '.', '');
  // group the non-handled variants by cause (verdict + failing probe kinds + the expectation's reason)
  const groups = new Map();
  for (const [vid, s] of all) {
    if (s.verdict === 'handled') continue;
    const x = e.verdicts[vid] ?? {};
    const key = JSON.stringify([s.verdict, kinds(s), x.why ?? '', x.upstream ?? null]);
    (groups.get(key) ?? groups.set(key, []).get(key)).push(vid);
  }
  out.push('| Verdict | Probes that failed | Cause | Upstream | Variants |', '|---|---|---|---|---|');
  for (const [k, vids] of [...groups].sort(([a], [b]) => (a < b ? -1 : 1))) {
    const [v, ks, why, up] = JSON.parse(k);
    const link = up ? (Array.isArray(up) ? up : [up]).map((u) => `[${u.replace(/^https:\/\/github.com\//, '').replace('/issues/', '#').replace('/pull/', '#')}](${u})`).join(', ') : 'none';
    out.push(`| ${v} | ${ks.join(', ')} | ${why} | ${link} | ${vids.length}: ${vids.slice(0, 6).map((x) => `\`${x}\``).join(', ')}${vids.length > 6 ? ', …' : ''} |`);
  }
  out.push('');
  const mem = main.sessions.map((s) => s.memory_peak_bytes ?? 0), ms = main.sessions.map((s) => s.ms ?? 0);
  out.push(`Peak indexer memory per session: ${(Math.max(...mem) / 2 ** 20).toFixed(0)} MiB at most. Session time: ${(Math.max(...ms) / 1000).toFixed(1)} s at most, ${(ms.reduce((a, b) => a + b, 0) / ms.length / 1000).toFixed(1)} s on average.`, '');
}
process.stdout.write(out.join('\n'));
